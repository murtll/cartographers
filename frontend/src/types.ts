// Формы данных, которыми обмениваемся с сервером. Имена полей — как в JSON, то есть
// в змеиной нотации: переименовывать их по пути в браузер значит держать в голове две
// таблицы имён вместо одной.
//
// Этот файл остаётся, когда заглушки из stubs.ts уедут: типы описывают договор с
// сервером, а заглушки его только заполняют.

/** Символ разметки планшета: обычная клетка, гора, руины, ущелье. */
export type BoardCell = '.' | 'M' | 'R' | 'C'

/**
 * Разметка планшета — то, что напечатано типографией. За партию не меняется ни на
 * клетку, поэтому в снапшоте её нет: браузер забирает её один раз запросом
 * `GET /api/boards/{id}` и держит как фон.
 */
export type BoardLayout = {
  id: string
  name: string
  /** 11 строк по 11 символов `BoardCell`. */
  grid: string[]
}

/**
 * Тип местности — то, что игрок рисует. Гор здесь нет намеренно: горы живут только в
 * разметке планшета, и выбрать их игрок не может никогда, даже если карта разрешает
 * любой тип местности.
 */
export type Terrain = 'empty' | 'forest' | 'village' | 'water' | 'farm' | 'monster'

/** Что предлагает открытая карта раунда. В M0.5 `shape_id` всегда `"single"`. */
export type MoveOption = {
  shape_id: string
  terrains: Terrain[]
}

/** Карта владений одного игрока: что он нарисовал и сколько монет закрасил. */
export type PlayerBoard = {
  /**
   * Сетка 11×11 нарисованного. Здесь только то, что игрок нарисовал сам, поэтому
   * клетка с горой приезжает как `"empty"` — горы берём из разметки.
   */
  drawn: Terrain[][]
  coins: number
}

export type Player = {
  id: string
  name: string
  /** Сдал ли игрок ход в этом раунде. */
  submitted: boolean
}

/**
 * Снапшот состояния партии: сервер присылает его целиком на каждое изменение, а не
 * разницей. Секретов в нём нет — порядок колоды в снапшот не попадает никогда.
 */
export type Snapshot = {
  /** Номер последнего применённого события; браузер помнит его, чтобы догнать пропущенное. */
  seq: number
  /** Пока известно только `"cartography"`, полный список значений не зафиксирован. */
  phase: string
  round: number
  /** Абсолютное время ISO 8601. Отсчёт рисует браузер, «время вышло» решает сервер. */
  deadline: string
  /** Кто из `players` — это я. Из-за этого поля снапшот собирается на игрока. */
  you: string
  board_id: string
  options: MoveOption[]
  /** Требование карты руин. В M0.5 всегда пустое. */
  constraint: null
  /** Карты владений всех игроков, ключ — идентификатор игрока. */
  boards: Record<string, PlayerBoard>
  players: Player[]
  /** Сколько карт осталось в колоде. Сколько — не секрет, какие именно — секрет. */
  deck_remaining: number
}
